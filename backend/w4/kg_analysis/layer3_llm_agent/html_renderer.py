# ---------------------------------------------------------------------------
# 辅助生成器
# ---------------------------------------------------------------------------

def _esc(text: str) -> str:
    """HTML 转义。"""
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def _render_text(text: str) -> str:
    """
    HTML 转义后，将正文中的 [N] 引用标注转为上标链接。
    例如：「AGENTPOISON [1] 是...」→ 「AGENTPOISON <sup class="cite"><a href="#ref-1">[1]</a></sup> 是...」
    """
    import re
    escaped = _esc(text)
    # 匹配 [数字] 或 [数字,数字,...] 形式
    def _replace(m: re.Match) -> str:
        nums = re.findall(r"\d+", m.group(0))
        sups = "".join(
            f'<sup class="cite"><a href="#ref-{n}" style="text-decoration:none">[{n}]</a></sup>'
            for n in nums
        )
        return sups
    return re.sub(r"\[[\d,\s]+\]", _replace, escaped)


def render_table(headers: list[str], rows: list[list[Any]]) -> str:
    """生成 HTML 表格。"""
    th = "".join(f"<th>{_esc(h)}</th>" for h in headers)
    body_rows = ""
    for row in rows:
        tds = "".join(f"<td>{_esc(cell)}</td>" for cell in row)
        body_rows += f"<tr>{tds}</tr>\n"
    return f"<table><thead><tr>{th}</tr></thead><tbody>{body_rows}</tbody></table>"


def render_bar_chart(
    chart_id: str,
    title: str,
    categories: list[str],
    series_name: str,
    values: list[int | float],
    *,
    color: str = "#5470c6",
    height: int = 360,
) -> str:
    """生成 ECharts 柱状图 HTML 片段。"""
    option = {
        "title": {"text": title, "textStyle": {"fontSize": 14}},
        "tooltip": {"trigger": "axis"},
        "xAxis": {
            "type": "category",
            "data": categories,
            "axisLabel": {"rotate": 30, "interval": 0},
        },
        "yAxis": {"type": "value"},
        "series": [{"name": series_name, "type": "bar",
                     "data": values, "itemStyle": {"color": color}}],
        "grid": {"left": "8%", "right": "4%", "bottom": "18%", "top": "15%"},
    }
    option_json = json.dumps(option, ensure_ascii=False)
    return (
        f'<div id="{chart_id}" class="chart-container" style="height:{height}px"></div>\n'
        f"<script>\n"
        f"(function(){{\n"
        f"  var c = echarts.init(document.getElementById('{chart_id}'));\n"
        f"  c.setOption({option_json});\n"
        f"  window.addEventListener('resize', function(){{ c.resize(); }});\n"
        f"}})();\n"
        f"</script>"
    )


def render_pie_chart(
    chart_id: str,
    title: str,
    data: list[dict[str, Any]],  # [{"name": ..., "value": ...}]
    *,
    height: int = 340,
) -> str:
    """生成 ECharts 饼图 HTML 片段。"""
    option = {
        "title": {"text": title, "textStyle": {"fontSize": 14},
                  "left": "center"},
        "tooltip": {"trigger": "item", "formatter": "{b}: {c} ({d}%)"},
        "legend": {"orient": "vertical", "left": "left"},
        "series": [{"name": title, "type": "pie", "radius": "55%",
                    "data": data, "emphasis": {"itemStyle": {
                        "shadowBlur": 10, "shadowOffsetX": 0,
                        "shadowColor": "rgba(0,0,0,0.5)"}}}],
    }
    option_json = json.dumps(option, ensure_ascii=False)
    return (
        f'<div id="{chart_id}" class="chart-container" style="height:{height}px"></div>\n'
        f"<script>\n"
        f"(function(){{\n"
        f"  var c = echarts.init(document.getElementById('{chart_id}'));\n"
        f"  c.setOption({option_json});\n"
        f"  window.addEventListener('resize', function(){{ c.resize(); }});\n"
        f"}})();\n"
        f"</script>"
    )


# ---------------------------------------------------------------------------
# HTMLReport — 逐步构建报告 DOM
# ---------------------------------------------------------------------------

class HTMLReport:
    """
    可逐步追加内容的 HTML 报告构建器。

    Usage:
        report = HTMLReport("报告标题", rq_id="RQ-001")
        report.add_section("研究背景", "<p>...</p>")
        report.add_table("数据统计", headers=[...], rows=[...])
        report.add_bar_chart("chart1", "分布图", categories=[...], values=[...])
        html = report.build()
    """

    def __init__(self, title: str, rq_id: str = "", meta_info: str = "") -> None:
        self.title = title
        self.rq_id = rq_id
        self.meta_info = meta_info
        self._sections: list[tuple[str, str]] = []  # (anchor_id, html_content)
        self._toc_entries: list[tuple[str, str]] = []  # (anchor_id, display_text)
        self._chart_counter = 0

    def _next_chart_id(self) -> str:
        self._chart_counter += 1
        return f"chart_{self._chart_counter}"

    def add_section(self, heading: str, html_content: str, level: int = 2) -> "HTMLReport":
        """添加一个章节（带标题和任意 HTML 内容）。"""
        anchor = "sec_" + re.sub(r"\W+", "_", heading).strip("_")
        tag = f"h{level}"
        block = (
            f'<{tag} id="{anchor}">{_esc(heading)}</{tag}>\n'
            f"{html_content}\n"
        )
        self._sections.append((anchor, block))
        if level == 2:
            self._toc_entries.append((anchor, heading))
        return self

    def add_paragraph(self, text: str) -> "HTMLReport":
        """在最后一个章节后追加段落（不加标题）。"""
        if self._sections:
            anchor, content = self._sections[-1]
            self._sections[-1] = (anchor, content + f"<p>{_esc(text)}</p>\n")
        return self

    def add_table(
        self,
        caption: str,
        headers: list[str],
        rows: list[list[Any]],
    ) -> "HTMLReport":
        """在最后一个章节中添加表格（带小标题）。"""
        html = f"<h3>{_esc(caption)}</h3>\n" + render_table(headers, rows)
        if self._sections:
            anchor, content = self._sections[-1]
            self._sections[-1] = (anchor, content + html + "\n")
        return self

    def add_bar_chart(
        self,
        title: str,
        categories: list[str],
        series_name: str,
        values: list[int | float],
        **kwargs: Any,
    ) -> "HTMLReport":
        """在最后一个章节中添加柱状图。"""
        chart_id = self._next_chart_id()
        html = render_bar_chart(chart_id, title, categories, series_name, values, **kwargs)
        if self._sections:
            anchor, content = self._sections[-1]
            self._sections[-1] = (anchor, content + html + "\n")
        return self

    def add_pie_chart(
        self,
        title: str,
        data: list[dict[str, Any]],
        **kwargs: Any,
    ) -> "HTMLReport":
        """在最后一个章节中添加饼图。"""
        chart_id = self._next_chart_id()
        html = render_pie_chart(chart_id, title, data, **kwargs)
        if self._sections:
            anchor, content = self._sections[-1]
            self._sections[-1] = (anchor, content + html + "\n")
        return self

    def add_note(self, text: str) -> "HTMLReport":
        """添加高亮提示块。"""
        html = f'<div class="note">{_render_text(text)}</div>\n'
        if self._sections:
            anchor, content = self._sections[-1]
            self._sections[-1] = (anchor, content + html)
        return self

    def add_references(
        self,
        entries: list[dict],  # [{"id": 1, "paper_id": "...", "title": "..."}]
    ) -> "HTMLReport":
        """添加参考文献列表（报告末尾）。"""
        if not entries:
            return self
        items = ""
        for e in entries:
            ref_id = _esc(str(e.get("id", "")))
            paper_id = _esc(str(e.get("paper_id", "")))
            title = _esc(str(e.get("title", paper_id)))
            paper_id_code = (
                f'&nbsp;<code style="font-size:0.82em;color:#888">{paper_id}</code>'
                if paper_id and paper_id != title
                else ""
            )
            items += (
                f'<li id="ref-{ref_id}" style="margin-bottom:4px">'
                f'<span class="ref-id">[{ref_id}]</span>&nbsp;'
                f'{title}{paper_id_code}'
                f'</li>\n'
            )
        html = (
            f'<div class="references">'
            f'<h2 id="sec_references">参考文献</h2>'
            f'<ol style="list-style:none;padding:0">{items}</ol>'
            f'</div>\n'
        )
        self._sections.append(("sec_references", html))
        return self

    def build(self) -> str:
        """生成完整 HTML 字符串。"""
        from datetime import datetime

        timestamp = datetime.now().strftime("%Y-%m-%d %H:%M")

        # 标题 + 元信息
        header_html = (
            f"<h1>{_esc(self.title)}</h1>\n"
            f'<div class="meta">{_esc(self.meta_info)}</div>\n'
            if self.meta_info
            else f"<h1>{_esc(self.title)}</h1>\n"
        )

        # 目录
        toc_html = ""
        if self._toc_entries:
            items = "".join(
                f'<li><a href="#{aid}">{_esc(text)}</a></li>\n'
                for aid, text in self._toc_entries
            )
            toc_html = f'<nav class="toc"><strong>目录</strong><ul>{items}</ul></nav>\n'

        body = header_html + toc_html + "\n".join(c for _, c in self._sections)

        return _HTML_BOILERPLATE.format(
            title=_esc(self.title),
            body=body,
            rq_id=_esc(self.rq_id),
            timestamp=timestamp,
        )

    def save(self, path: str) -> None:
        """写入 HTML 文件。"""
        import os
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(self.build())


