# 从 LLM 输出自动渲染（解析 LLM 返回的结构化 sections）
# ---------------------------------------------------------------------------

def render_from_llm_output(
    llm_sections: list[dict[str, Any]],
    title: str,
    rq_id: str = "",
    meta_info: str = "",
) -> str:
    """
    将 LLM 输出的 sections 列表渲染为 HTML。

    llm_sections 格式（LLM 生成的 JSON 数组）：
    [
      {
        "type": "section",
        "heading": "研究背景",
        "content": "..."           ← 正文文本
      },
      {
        "type": "table",
        "heading": "数据统计",
        "headers": ["列1","列2"],
        "rows": [["v1","v2"], ...]
      },
      {
        "type": "bar_chart",
        "heading": "分布图",
        "categories": ["A","B","C"],
        "series_name": "数量",
        "values": [10, 5, 3]
      },
      {
        "type": "pie_chart",
        "heading": "占比分布",
        "data": [{"name":"A","value":10}, ...]
      },
      {
        "type": "note",
        "content": "注意：..."
      }
    ]
    """
    report = HTMLReport(title, rq_id=rq_id, meta_info=meta_info)

    for item in llm_sections:
        item_type = item.get("type", "section")
        heading = item.get("heading", "")

        if item_type == "section":
            content_raw = item.get("content", "")
            # 换行转段落，每段用 _render_text 处理引用标注
            paras = content_raw.split("\n")
            content_html = "".join(
                f"<p>{_render_text(p)}</p>" for p in paras if p.strip()
            )
            report.add_section(heading, content_html)

        elif item_type == "table":
            if not heading:
                heading = item.get("caption", "数据表")
            # 先建一个空 section 再加表（保证 caption 层级正确）
            if not report._sections or report._sections[-1][0].startswith("sec_"):
                pass  # 追加到当前章节
            report.add_table(
                heading,
                headers=item.get("headers", []),
                rows=item.get("rows", []),
            )

        elif item_type == "bar_chart":
            report.add_bar_chart(
                title=heading or item.get("title", ""),
                categories=item.get("categories", []),
                series_name=item.get("series_name", ""),
                values=item.get("values", []),
            )

        elif item_type == "pie_chart":
            report.add_pie_chart(
                title=heading or item.get("title", ""),
                data=item.get("data", []),
            )

        elif item_type == "note":
            report.add_note(item.get("content", ""))

        elif item_type == "references":
            report.add_references(item.get("entries", []))

    return report.build()


